#!/usr/bin/env python3
"""A geometrically degenerate scene for testing SLAM: the DARPA SubT tunnel staging area (with its barriers, base
station and fiducial, placed as in tunnel_circuit_practice_01) followed by one long straight tunnel of identical straight
tiles (Tunnel Tile 5 of the SubT tunnel circuit: 20 m long, 6 m wide, 4 m high, ribbed walls), closed by a blocker.
Inside it, a scan constrains everything but the motion along the tunnel, as long as the closed end stays out of the
lidar's range (Livox Avia: 190 m; Ouster OS0: 50 m): 1000 m (the default) leaves ~800 m of degenerate tunnel for the
Avia, entrance to 190 m before the end.
Writes assets/subt/worlds/long_tunnel_<length>m.sdf (tiles from Gazebo Fuel, Open Robotics, CC BY 4.0; fetched with
the other models by tools/add_scenes.sh), then:
  python3 tools/make_long_tunnel.py [LENGTH_M=1000]     a multiple of 20 m
  tools/add_scenes.sh long_tunnel_1000m                 convert -> sim/scenes/long_tunnel_1000m.usd
  ./sim.sh --scene long_tunnel_1000m                    start pose (2, 0), facing the tunnel (config/scenes.yaml)
The tunnel runs along +x from x = 10 m (the staging area's exit) to x = 10 + LENGTH_M."""
import os
import sys

FUEL = "https://fuel.ignitionrobotics.org/1.0/OpenRobotics/models/"
TILE = 20.0   # m, SubT tile grid
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# staging area and its surroundings, as in tunnel_circuit_practice_01 (osrf/subt, Apache-2.0)
START = [("staging_area", "subt_tunnel_staging_area", (0, 0, 0, 0)), ("base_station", "Base Station", (-8, 0, 0, -1.5708)),
         ("fiducial", "Fiducial", (10, 0, 0, 0))] + \
        [(f"barrier_{i}", "Jersey Barrier", (x, y, 0, 0)) for i, (x, y) in enumerate(
            [(8.0, -11), (8.0, 11), (3.7, -11), (3.7, 11), (-0.6, -11), (-0.6, 11), (-4.9, -11), (-4.9, 11), (-9.2, -11),
             (-9.2, 11), (10.5, -8.6), (10.5, 8.6), (-12, -8.6), (-12, -4.3), (-12, 0.0), (-12, 4.3), (-12, 8.6)])]


def world(length_m):
    n = int(round(length_m / TILE))
    assert n >= 1 and abs(n * TILE - length_m) < 1e-6, "LENGTH_M must be a positive multiple of 20 m"
    parts = START + [(f"tile_{i}", "Tunnel Tile 5", (TILE * i, 0, 0, 1.570796)) for i in range(1, n + 1)] + \
        [("blocker_end", "Tunnel Tile Blocker", (TILE * n + 11, 0, 0, 0))]   # Tile 5 runs along y: turned onto +x
    inc = "".join(f"""
    <include>
      <static>true</static>
      <name>{name}</name>
      <pose>{x} {y} {z} 0 0 {yaw}</pose>
      <uri>{FUEL}{model}</uri>
    </include>""" for name, model, (x, y, z, yaw) in parts)
    name = f"long_tunnel_{int(length_m)}m"
    return name, n, f"""<?xml version="1.0" ?>
<!-- Generated by tools/make_long_tunnel.py {int(length_m)}: staging area + {n} x Tunnel Tile 5 along +x + blocker -->
<sdf version="1.6">
  <world name="{name}">
    <scene>
      <ambient>0.1 0.1 0.1 1.0</ambient>
      <background>0 0 0 1.0</background>
      <grid>false</grid>
    </scene>{inc}
  </world>
</sdf>
"""


def selftest():
    name, n, s = world(60)
    assert name == "long_tunnel_60m" and n == 3 and s.count("Tunnel Tile 5</uri>") == 3 and s.count("<include>") == 20 + 3 + 1
    assert "<pose>60.0 0 0 0 0 1.570796</pose>" in s and "<pose>71.0 0 0 0 0 0</pose>" in s   # last tile, blocker
    for bad in (0, 30):
        try:
            world(bad)
        except AssertionError:
            continue
        raise AssertionError(f"{bad} m accepted")
    print("selftest ok")


if __name__ == "__main__":
    if sys.argv[1:] == ["--selftest"]:
        selftest()
        sys.exit()
    name, n, sdf = world(float(sys.argv[1]) if len(sys.argv) > 1 else 1000.0)
    out = os.path.join(ROOT, "assets", "subt", "worlds", name + ".sdf")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, "w").write(sdf)
    print(f"{out}: {n} straight tiles, tunnel x = 10 .. {10 + n * TILE:.0f} m\nnext: tools/add_scenes.sh {name}")
